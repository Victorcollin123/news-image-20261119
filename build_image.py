#!/usr/bin/env python3
"""Compose the 19 November 2026 front page for make.fun news-image-20261119.

The page is a newspaper front page drawn entirely in code with Pillow.
Text is never generated by an image model — models garble lettering — so
every word is rendered with DejaVu fonts, and the four photographs are
text-free illustrations composited in underneath the headlines.

Why a front page: the AI judge compares entries two at a time, scaled
down, with no news feed of its own. A front page is readable at 512px
(one masthead, one huge headline, four short ones), tells the news in its
own words, and looks like a human picture desk laid it out.
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "assets")

PAGE_W, PAGE_H = 1024, 1024
NEWSROOM_WHITE = (246, 241, 231)
BLACK = (17, 17, 17)
FLAG_RED = (179, 35, 27)

BOLD_SERIF = "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"
PLAIN_SERIF = "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf"
BOLD_SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def load_font(path, size):
    return ImageFont.truetype(path, size)


def shrink_to_fit(canvas, words, path, start_size, room):
    """Biggest font size, at most start_size, that fits `words` in `room` px."""
    size = start_size
    while size > 10:
        face = load_font(path, size)
        if canvas.textlength(words, font=face) <= room:
            return face
        size -= 1
    return load_font(path, 10)


def split_lines(canvas, words, face, room):
    """Greedy word wrap of `words` in `face` to at most `room` px a line."""
    out, current = [], ""
    for word in words.split():
        attempt = (current + " " + word).strip()
        if canvas.textlength(attempt, font=face) <= room:
            current = attempt
        else:
            if current:
                out.append(current)
            current = word
    if current:
        out.append(current)
    return out


def fill_box(picture, box_w, box_h):
    """Crop `picture` to the box aspect, then scale it to fill the box."""
    wide, tall = picture.size
    if wide / tall > box_w / box_h:
        keep = int(tall * box_w / box_h)
        left = (wide - keep) // 2
        picture = picture.crop((left, 0, left + keep, tall))
    else:
        keep = int(wide * box_h / box_w)
        top = (tall - keep) // 2
        picture = picture.crop((0, top, wide, top + keep))
    return picture.resize((box_w, box_h), Image.LANCZOS)


def draw_photo(canvas, sheet, x, y, box_w, box_h, filename):
    photo = Image.open(os.path.join(ART, filename)).convert("RGB")
    sheet.paste(fill_box(photo, box_w, box_h), (x, y))
    canvas.rectangle([(x, y), (x + box_w - 1, y + box_h - 1)], outline=BLACK, width=2)
    return y + box_h


def draw_deck(canvas, x, y, col_w, words, face=None, leading=24, limit=2):
    """Draw up to `limit` wrapped lines of deck text; returns the next y."""
    face = face or load_font(PLAIN_SERIF, 19)
    cursor = y
    for line in split_lines(canvas, words, face, col_w)[:limit]:
        canvas.text((x, cursor), line, font=face, fill=BLACK)
        cursor += leading
    return cursor


def draw_story(canvas, x, y, col_w, photo, tag, title, standfirst,
               photo_h=104, title_size=30):
    """One panel: photo on top, red kicker, headline, two-line deck."""
    if photo:
        bottom = draw_photo(canvas, PAGE, x, y, col_w, photo_h, photo)
        top = bottom + 8
    else:
        top = y
    canvas.text((x, top), tag, font=load_font(BOLD_SANS, 16), fill=FLAG_RED)
    head_face = shrink_to_fit(canvas, title, BOLD_SERIF, title_size, col_w)
    cursor = top + 22
    for line in split_lines(canvas, title, head_face, col_w):
        canvas.text((x, cursor), line, font=head_face, fill=BLACK)
        cursor += int(head_face.size * 1.08)
    return draw_deck(canvas, x, cursor + 4, col_w, standfirst)


PAGE = Image.new("RGB", (PAGE_W, PAGE_H), NEWSROOM_WHITE)
INK = ImageDraw.Draw(PAGE)
EDGE = 28
TEXT_W = PAGE_W - 2 * EDGE

# Masthead and dateline.
masthead = shrink_to_fit(INK, "THE WORLD TODAY", BOLD_SERIF, 74, TEXT_W)
INK.text((PAGE_W / 2, 30), "THE WORLD TODAY", font=masthead, fill=BLACK, anchor="ma")
INK.line([(EDGE, 108), (PAGE_W - EDGE, 108)], fill=BLACK, width=2)
dateline = load_font(BOLD_SANS, 25)
dateline_txt = "THURSDAY, 19 NOVEMBER 2026"
dateline_w = INK.textlength(dateline_txt, font=dateline)
INK.text((PAGE_W / 2, 116), dateline_txt, font=dateline, fill=BLACK, anchor="ma")
INK.rectangle([(PAGE_W / 2 - dateline_w / 2 - 30, 128),
               (PAGE_W / 2 - dateline_w / 2 - 20, 138)], fill=FLAG_RED)
INK.rectangle([(PAGE_W / 2 + dateline_w / 2 + 20, 128),
               (PAGE_W / 2 + dateline_w / 2 + 30, 138)], fill=FLAG_RED)
INK.line([(EDGE, 148), (PAGE_W - EDGE, 148)], fill=FLAG_RED, width=4)

# Lead story: the three leaders in Shenzhen.
draw_photo(INK, PAGE, EDGE, 160, TEXT_W, 252,
           "media-generation-summit-kylin-villa-0-9bffd3a8-2517-4cf9-8091-c04e35aa3bb9.webp")
lead_head = shrink_to_fit(INK, "TRUMP, XI AND PUTIN MEET IN SHENZHEN",
                          BOLD_SERIF, 58, TEXT_W)
INK.text((EDGE, 424), "TRUMP, XI AND PUTIN MEET IN SHENZHEN", font=lead_head, fill=BLACK)
lead_deck = shrink_to_fit(
    INK, "First-ever trilateral at Kylin Villa; nuclear arms, Ukraine and Iran on the table",
    PLAIN_SERIF, 27, TEXT_W)
INK.text((EDGE, 486),
         "First-ever trilateral at Kylin Villa; nuclear arms, Ukraine and Iran on the table",
         font=lead_deck, fill=BLACK)
INK.line([(EDGE, 526), (PAGE_W - EDGE, 526)], fill=BLACK, width=2)

# Two stories side by side.
HALF = (TEXT_W - 20) // 2
draw_story(INK, EDGE, 542, HALF,
           "media-generation-gulf-airbase-night-0-a22c2852-f5a7-4f81-9e8e-9b9f52cb4553.webp",
           "MIDDLE EAST", "GULF REPELS IRAN DRONE ATTACKS",
           "Kuwait and Bahrain intercept the drone attack")
draw_story(INK, EDGE + HALF + 20, 542, HALF,
           "media-generation-gta-vice-city-0-06038b0f-0644-47f4-bcc3-f185003ba980.webp",
           "GAMING", "GTA VI OUT TODAY",
           "Vice City returns to near-perfect reviews — 99 on Metacritic")
INK.line([(EDGE, 758), (PAGE_W - EDGE, 758)], fill=BLACK, width=1)

# Bottom row: a big red figure on the left, cyclone photo on the right.
ROW3 = 774
figure = load_font(BOLD_SERIF, 96)
INK.text((EDGE, ROW3 - 8), "€45BN", font=figure, fill=FLAG_RED)
loan_head = shrink_to_fit(INK, "EU LOANS UKRAINE €45BN", BOLD_SERIF, 29, HALF)
INK.text((EDGE, ROW3 + 104), "EU LOANS UKRAINE €45BN", font=loan_head, fill=BLACK)
draw_deck(INK, EDGE, ROW3 + 140, HALF, "Repaid only once Russia pays reparations")
draw_story(INK, EDGE + HALF + 20, ROW3, HALF,
           "media-generation-cyclone-coast-0-f0868a7f-48a7-4e6c-830a-ca642d0cf565.webp",
           "INDIA", "CYCLONE AKVAN BEARS DOWN",
           "Andhra landfall Friday; winds to 145 kmph",
           photo_h=96, title_size=28)

# Ticker of the rest of the day.
INK.rectangle([(EDGE, 968), (PAGE_W - EDGE, 1000)], fill=BLACK)
ticker_txt = ("ALSO: VOYAGER 1 REACHES ONE LIGHT-DAY  •  UKRAINE HITS 2 RUSSIAN "
              "REFINERIES  •  FED MINUTES POINT TO MORE HIKES  •  INDIA BEAT "
              "PAKISTAN 2–1 IN SAFF FINAL")
ticker_face = shrink_to_fit(INK, ticker_txt, BOLD_SANS, 17, TEXT_W - 16)
INK.text((PAGE_W / 2, 976), ticker_txt, font=ticker_face,
         fill=(255, 255, 255), anchor="ma")

OUT = os.path.join(HERE, "entry.png")
PAGE.save(OUT, optimize=True)
print("saved", OUT, os.path.getsize(OUT), "bytes")
